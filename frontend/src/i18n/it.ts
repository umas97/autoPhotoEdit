export type StringKey = keyof typeof it

/**
 * The one way a component gets a visible string.
 *
 * `{name}` placeholders are replaced from `vars`; an unknown key returns itself,
 * which is loud in the interface and harmless in production.
 */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  const template: string = it[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  )
}
